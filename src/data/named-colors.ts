export const COLOR_GROUPS: readonly ColorGroup[] = ['CSS', 'Tailwind', 'Developer']

export function normalizeColorName(input: string): string {
  return input.toLowerCase().replace(/[^a-z0-9]+/g, '')
}

let lookup: Map<string, NamedColor> | null = null

export function findNamedColor(input: string): NamedColor | undefined {
  if (!lookup) {
    lookup = new Map()
    for (const color of NAMED_COLORS) {
      for (const name of [color.name, ...(color.aliases ?? [])]) {
        const key = normalizeColorName(name)
        if (!lookup.has(key)) lookup.set(key, color)
      }
    }
  }
  return lookup.get(normalizeColorName(input))
}
